-- Protege gabaritos e cadastra links oficiais para provas reais.
-- Questões de terceiros só são reproduzidas depois de comprovar licença/autorização.
alter table public.study_questions
  drop constraint if exists study_questions_answer_matches_option;
alter table public.study_questions
  drop column if exists answer;

create table if not exists public.study_question_answers (
  question_id bigint primary key references public.study_questions(id) on delete cascade,
  answer text not null check (char_length(btrim(answer)) between 1 and 8),
  explanation text not null default '' check (char_length(explanation) <= 5000),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.study_question_answers enable row level security;

drop policy if exists "Admins can manage study question answers" on public.study_question_answers;
create policy "Admins can manage study question answers"
  on public.study_question_answers for all to authenticated
  using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin')
  with check (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin');
grant select, insert, update, delete on public.study_question_answers to authenticated;

create or replace function public.check_study_question_answer(
  p_question_id bigint,
  p_selected_answer text
)
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select jsonb_build_object(
    'correct', a.answer = btrim(coalesce(p_selected_answer, '')),
    'explanation', a.explanation
  )
  from public.study_questions q
  join public.study_question_answers a on a.question_id = q.id
  where q.id = p_question_id
    and q.published = true
    and q.license_status in ('permission_granted','public_domain','cc_by','cc_by_sa')
    and auth.uid() is not null
  limit 1;
$$;
revoke all on function public.check_study_question_answer(bigint, text) from public, anon;
grant execute on function public.check_study_question_answer(bigint, text) to authenticated;

create table if not exists public.study_exam_sources (
  id bigint generated by default as identity primary key,
  board text not null check (char_length(btrim(board)) between 2 and 80),
  exam_name text not null check (char_length(btrim(exam_name)) between 2 and 220),
  exam_year integer not null check (exam_year between 1900 and 2200),
  discipline text not null default 'Diversas disciplinas',
  role_name text not null default '',
  source_url text not null check (source_url ~ '^https://'),
  exam_url text check (exam_url is null or exam_url ~ '^https://'),
  answer_key_url text check (answer_key_url is null or answer_key_url ~ '^https://'),
  notes text not null default '',
  verified_at timestamptz not null default now(),
  published boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists study_exam_sources_public_idx
  on public.study_exam_sources(board, exam_year desc) where published = true;
alter table public.study_exam_sources enable row level security;

drop policy if exists "Public can read official exam sources" on public.study_exam_sources;
create policy "Public can read official exam sources"
  on public.study_exam_sources for select to anon, authenticated
  using (published = true);

drop policy if exists "Admins can manage official exam sources" on public.study_exam_sources;
create policy "Admins can manage official exam sources"
  on public.study_exam_sources for all to authenticated
  using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin')
  with check (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin');
grant select on public.study_exam_sources to anon, authenticated;
grant insert, update, delete on public.study_exam_sources to authenticated;
grant usage, select on sequence public.study_exam_sources_id_seq to authenticated;

