-- Banco de questões e histórico de simulados do EditalRadar.
-- Reproduza esta migração depois de 202611220004_auto_publish.sql.
alter table public.user_data
  add column if not exists question_progress jsonb not null
  default '{"attempts":[],"saved":[],"simulations":[]}'::jsonb;

create table if not exists public.study_questions (
  id bigint generated by default as identity primary key,
  discipline text not null check (char_length(btrim(discipline)) between 2 and 100),
  topic text not null check (char_length(btrim(topic)) between 2 and 160),
  difficulty text not null check (difficulty in ('Fácil','Intermediária','Avançada')),
  board text not null check (char_length(btrim(board)) between 2 and 80),
  exam_name text not null check (char_length(btrim(exam_name)) between 2 and 180),
  exam_year integer not null check (exam_year between 1900 and 2200),
  prompt text not null check (char_length(btrim(prompt)) between 10 and 5000),
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) between 2 and 6),
  answer text not null check (char_length(btrim(answer)) between 1 and 8),
  explanation text not null default '' check (char_length(explanation) <= 5000),
  source_url text not null check (source_url ~ '^https://'),
  rights_holder text not null check (char_length(btrim(rights_holder)) between 2 and 180),
  license_status text not null check (license_status in ('permission_granted','public_domain','cc_by','cc_by_sa','link_only')),
  license_proof_url text check (license_proof_url is null or license_proof_url ~ '^https://'),
  published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint study_questions_answer_matches_option
    check (options @> jsonb_build_array(answer))
);

create index if not exists study_questions_published_discipline_idx
  on public.study_questions(discipline, board, difficulty, exam_year desc)
  where published = true;
create index if not exists study_questions_search_idx
  on public.study_questions using gin (
    to_tsvector('portuguese', coalesce(prompt,'') || ' ' || coalesce(topic,'') || ' ' || coalesce(exam_name,''))
  );

alter table public.study_questions enable row level security;

drop policy if exists "Public can read licensed published questions" on public.study_questions;
create policy "Public can read licensed published questions"
  on public.study_questions for select to anon, authenticated
  using (
    published = true
    and license_status in ('permission_granted','public_domain','cc_by','cc_by_sa')
    and (license_status = 'public_domain' or license_proof_url is not null)
  );

drop policy if exists "Admins can read all study questions" on public.study_questions;
create policy "Admins can read all study questions"
  on public.study_questions for select to authenticated
  using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin');

drop policy if exists "Admins can insert study questions" on public.study_questions;
create policy "Admins can insert study questions"
  on public.study_questions for insert to authenticated
  with check (
    coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin'
    and created_by = (select auth.uid())
  );

drop policy if exists "Admins can update study questions" on public.study_questions;
create policy "Admins can update study questions"
  on public.study_questions for update to authenticated
  using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin')
  with check (
    coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin'
    and created_by = (select auth.uid())
  );

drop policy if exists "Admins can delete study questions" on public.study_questions;
create policy "Admins can delete study questions"
  on public.study_questions for delete to authenticated
  using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), '') = 'admin');

grant select on public.study_questions to anon, authenticated;
grant insert, update, delete on public.study_questions to authenticated;
grant usage, select on sequence public.study_questions_id_seq to authenticated;
