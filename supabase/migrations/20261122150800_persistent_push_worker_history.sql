-- Durable, aggregated execution history for the scheduled push worker.
-- The private table stores counts only: no FCM tokens, user IDs, or notification content.

create schema if not exists private;

create table if not exists private.push_worker_runs (
  id bigint generated by default as identity primary key,
  recorded_at timestamptz not null default now(),
  duration_ms integer not null default 0 check (duration_ms >= 0),
  processed integer not null default 0 check (processed >= 0),
  sent integer not null default 0 check (sent >= 0),
  rescheduled integer not null default 0 check (rescheduled >= 0),
  expired integer not null default 0 check (expired >= 0),
  expired_before_retry integer not null default 0 check (expired_before_retry >= 0),
  disabled_invalid integer not null default 0 check (disabled_invalid >= 0),
  invalid_message integer not null default 0 check (invalid_message >= 0),
  dead_letter integer not null default 0 check (dead_letter >= 0),
  pending_redelivery integer not null default 0 check (pending_redelivery >= 0)
);

create index if not exists push_worker_runs_recorded_at_idx
  on private.push_worker_runs (recorded_at desc);

alter table private.push_worker_runs enable row level security;
revoke all on table private.push_worker_runs from public, anon, authenticated;
grant usage on schema private to service_role;
grant insert on table private.push_worker_runs to service_role;
revoke all on sequence private.push_worker_runs_id_seq from public, anon, authenticated;
grant usage, select on sequence private.push_worker_runs_id_seq to service_role;

comment on table private.push_worker_runs is
  'Histórico operacional agregado do worker FCM; não armazena tokens, IDs de usuários nem conteúdo de notificações.';

create or replace function public.record_push_worker_run(p_counts jsonb)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_id bigint;
begin
  if current_user <> 'service_role' then
    raise exception 'Acesso restrito ao serviço de notificações'
      using errcode = '42501';
  end if;

  if jsonb_typeof(p_counts) is distinct from 'object' then
    raise exception 'Invalid push worker metrics';
  end if;

  insert into private.push_worker_runs (
    duration_ms,
    processed,
    sent,
    rescheduled,
    expired,
    expired_before_retry,
    disabled_invalid,
    invalid_message,
    dead_letter,
    pending_redelivery
  ) values (
    greatest(0, least(coalesce(nullif(p_counts ->> 'duration_ms', '')::integer, 0), 55000)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'processed', '')::integer, 0), 20)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'sent', '')::integer, 0), 20)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'rescheduled', '')::integer, 0), 20)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'expired', '')::integer, 0), 20)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'expired_before_retry', '')::integer, 0), 20)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'disabled_invalid', '')::integer, 0), 20)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'invalid_message', '')::integer, 0), 20)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'dead_letter', '')::integer, 0), 20)),
    greatest(0, least(coalesce(nullif(p_counts ->> 'pending_redelivery', '')::integer, 0), 20))
  )
  returning id into v_id;

  -- Keep a rolling 30-day window; at most one routine deletion per scheduler tick.
  delete from private.push_worker_runs
  where recorded_at < now() - interval '30 days';

  return v_id;
end;
$function$;

comment on function public.record_push_worker_run(jsonb) is
  'Grava somente contagens agregadas do worker. Chamável exclusivamente por service_role.';

revoke all on function public.record_push_worker_run(jsonb) from public, anon, authenticated;
grant execute on function public.record_push_worker_run(jsonb) to service_role;

create or replace function private._get_push_notification_health()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_queue jsonb;
  v_scheduler jsonb;
  v_http jsonb;
  v_devices jsonb;
  v_failures jsonb;
  v_recent_errors jsonb;
begin
  if auth.uid() is null
    or coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'admin'
  then
    raise exception 'Acesso restrito a administradores'
      using errcode = '42501';
  end if;

  select jsonb_build_object(
    'queue_length', coalesce(metrics.queue_length, 0),
    'visible_length', coalesce(metrics.queue_visible_length, 0),
    'oldest_message_age_seconds', metrics.oldest_msg_age_sec,
    'newest_message_age_seconds', metrics.newest_msg_age_sec,
    'total_messages', coalesce(metrics.total_messages, 0),
    'scraped_at', metrics.scrape_time
  )
  into v_queue
  from pgmq.metrics('push_delivery_retries') as metrics
  where metrics.queue_name = 'push_delivery_retries';

  if v_queue is null then
    v_queue := jsonb_build_object(
      'queue_length', 0,
      'visible_length', 0,
      'oldest_message_age_seconds', null,
      'newest_message_age_seconds', null,
      'total_messages', 0,
      'scraped_at', now()
    );
  end if;

  select jsonb_build_object(
    'active', job.active,
    'schedule', job.schedule,
    'last_run_at', run.start_time,
    'last_run_finished_at', run.end_time,
    'last_run_status', run.status,
    'last_run_message', run.return_message,
    'last_run_age_seconds', case
      when run.start_time is null then null
      else greatest(0, extract(epoch from (now() - run.start_time))::integer)
    end
  )
  into v_scheduler
  from cron.job as job
  left join lateral (
    select details.start_time, details.end_time, details.status, details.return_message
    from cron.job_run_details as details
    where details.jobid = job.jobid
    order by details.start_time desc
    limit 1
  ) as run on true
  where job.jobname = 'process-push-delivery-retries'
  limit 1;

  if v_scheduler is null then
    v_scheduler := jsonb_build_object(
      'active', false,
      'schedule', null,
      'last_run_at', null,
      'last_run_finished_at', null,
      'last_run_status', null,
      'last_run_message', null,
      'last_run_age_seconds', null
    );
  end if;

  select jsonb_build_object(
    'status_code', response.status_code,
    'created_at', response.created,
    'timed_out', coalesce(response.timed_out, false),
    'error', nullif(left(coalesce(response.error_msg, ''), 240), ''),
    'result_counts', jsonb_build_object(
      'available', parsed.processed_match is not null,
      'processed', coalesce((parsed.processed_match)[1]::integer, 0),
      'sent', coalesce((parsed.sent_match)[1]::integer, 0),
      'rescheduled', coalesce((parsed.rescheduled_match)[1]::integer, 0),
      'expired', coalesce((parsed.expired_match)[1]::integer, 0),
      'expired_before_retry', coalesce((parsed.expired_before_retry_match)[1]::integer, 0),
      'disabled_invalid', coalesce((parsed.disabled_invalid_match)[1]::integer, 0),
      'invalid_message', coalesce((parsed.invalid_message_match)[1]::integer, 0),
      'dead_letter', coalesce((parsed.dead_letter_match)[1]::integer, 0),
      'pending_redelivery', coalesce((parsed.pending_redelivery_match)[1]::integer, 0)
    )
  )
  into v_http
  from net._http_response as response
  cross join lateral (
    select
      regexp_match(coalesce(response.content, ''), '"processed"\s*:\s*([0-9]+)') as processed_match,
      regexp_match(coalesce(response.content, ''), '"sent"\s*:\s*([0-9]+)') as sent_match,
      regexp_match(coalesce(response.content, ''), '"rescheduled"\s*:\s*([0-9]+)') as rescheduled_match,
      regexp_match(coalesce(response.content, ''), '"expired"\s*:\s*([0-9]+)') as expired_match,
      regexp_match(coalesce(response.content, ''), '"expired_before_retry"\s*:\s*([0-9]+)') as expired_before_retry_match,
      regexp_match(coalesce(response.content, ''), '"disabled_invalid"\s*:\s*([0-9]+)') as disabled_invalid_match,
      regexp_match(coalesce(response.content, ''), '"invalid_message"\s*:\s*([0-9]+)') as invalid_message_match,
      regexp_match(coalesce(response.content, ''), '"dead_letter"\s*:\s*([0-9]+)') as dead_letter_match,
      regexp_match(coalesce(response.content, ''), '"pending_redelivery"\s*:\s*([0-9]+)') as pending_redelivery_match
  ) as parsed
  order by response.created desc
  limit 1;

  if v_http is null then
    v_http := jsonb_build_object(
      'status_code', null,
      'created_at', null,
      'timed_out', false,
      'error', null,
      'result_counts', jsonb_build_object(
        'available', false,
        'processed', 0,
        'sent', 0,
        'rescheduled', 0,
        'expired', 0,
        'expired_before_retry', 0,
        'disabled_invalid', 0,
        'invalid_message', 0,
        'dead_letter', 0,
        'pending_redelivery', 0
      )
    );
  end if;

  select jsonb_build_object(
    'total', count(*),
    'enabled', count(*) filter (where enabled is true),
    'disabled', count(*) filter (where enabled is false)
  )
  into v_devices
  from public.push_devices;

  select jsonb_build_object(
    'total', count(*),
    'last_24h', count(*) filter (where failed_at >= now() - interval '24 hours'),
    'latest_at', max(failed_at)
  )
  into v_failures
  from public.push_delivery_failures;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'error_code', grouped.error_code,
        'count', grouped.failure_count,
        'latest_at', grouped.latest_at
      )
      order by grouped.latest_at desc
    ),
    '[]'::jsonb
  )
  into v_recent_errors
  from (
    select error_code, count(*) as failure_count, max(failed_at) as latest_at
    from public.push_delivery_failures
    where failed_at >= now() - interval '7 days'
    group by error_code
    order by max(failed_at) desc
    limit 5
  ) as grouped;

  select jsonb_build_object(
    'available', latest.id is not null,
    'last_run_at', latest.recorded_at,
    'last_duration_ms', coalesce(latest.duration_ms, 0),
    'runs_24h', coalesce(summary.runs_24h, 0),
    'processed_24h', coalesce(summary.processed_24h, 0),
    'sent_24h', coalesce(summary.sent_24h, 0),
    'rescheduled_24h', coalesce(summary.rescheduled_24h, 0),
    'expired_24h', coalesce(summary.expired_24h, 0),
    'disabled_invalid_24h', coalesce(summary.disabled_invalid_24h, 0),
    'dead_letter_24h', coalesce(summary.dead_letter_24h, 0),
    'pending_redelivery_24h', coalesce(summary.pending_redelivery_24h, 0),
    'latest', case when latest.id is null then null else jsonb_build_object(
      'available', true,
      'processed', latest.processed,
      'sent', latest.sent,
      'rescheduled', latest.rescheduled,
      'expired', latest.expired,
      'expired_before_retry', latest.expired_before_retry,
      'disabled_invalid', latest.disabled_invalid,
      'invalid_message', latest.invalid_message,
      'dead_letter', latest.dead_letter,
      'pending_redelivery', latest.pending_redelivery,
      'duration_ms', latest.duration_ms
    ) end
  )
  into v_worker_history
  from (
    select
      count(*) filter (where recorded_at >= now() - interval '24 hours') as runs_24h,
      coalesce(sum(processed) filter (where recorded_at >= now() - interval '24 hours'), 0) as processed_24h,
      coalesce(sum(sent) filter (where recorded_at >= now() - interval '24 hours'), 0) as sent_24h,
      coalesce(sum(rescheduled) filter (where recorded_at >= now() - interval '24 hours'), 0) as rescheduled_24h,
      coalesce(sum(expired + expired_before_retry) filter (where recorded_at >= now() - interval '24 hours'), 0) as expired_24h,
      coalesce(sum(disabled_invalid) filter (where recorded_at >= now() - interval '24 hours'), 0) as disabled_invalid_24h,
      coalesce(sum(dead_letter) filter (where recorded_at >= now() - interval '24 hours'), 0) as dead_letter_24h,
      coalesce(sum(pending_redelivery) filter (where recorded_at >= now() - interval '24 hours'), 0) as pending_redelivery_24h
    from private.push_worker_runs
  ) as summary
  left join lateral (
    select *
    from private.push_worker_runs
    order by recorded_at desc
    limit 1
  ) as latest on true;

  if coalesce((v_worker_history ->> 'available')::boolean, false) then
    v_http := jsonb_set(v_http, '{result_counts}', v_worker_history -> 'latest', true);
  end if;

  return jsonb_build_object(
    'generated_at', now(),
    'queue', v_queue,
    'scheduler', v_scheduler,
    'worker_http', v_http,
    'worker_history', v_worker_history,
    'devices', v_devices,
    'failures', v_failures,
    'recent_errors', v_recent_errors
  );
end;
$function$;

comment on function private._get_push_notification_health() is
  'Consulta administrativa de push com histórico agregado de 24 horas, sem payloads ou tokens.';